"""Generate the event streams the docs demo replays (docs/demo/streams.js).

The page never models typing itself: every keystroke it plays comes from
here. Run after changing the engine, the profile or the seeds:

    python scripts/gen_demo_streams.py
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from humaninput import profile as profiles  # noqa: E402
from humaninput.backends import json as json_backend  # noqa: E402
from humaninput.typing.typist import Typist  # noqa: E402

OUT = ROOT / "docs" / "demo" / "streams.js"
TEXT = "Amsterdam"
PROFILE = "hunt_and_peck"
# Seeds 1, 7, 8, 10 and 12 fail in examples/autocomplete-race; seed 0 passes.
# 10 and 12 lose the race by under 60 ms, too close for real-time browser timers.
SEEDS = [7, 1, 8, 0]


def build() -> str:
    prof = profiles.load(PROFILE)
    streams = [
        json.loads(json_backend.to_json(Typist(profile=prof, seed=seed).type(TEXT)))
        for seed in SEEDS
    ]
    payload = json.dumps({"text": TEXT, "profile": PROFILE, "streams": streams}, separators=(",", ":"))
    # A script, not a .json file, so the page also works when opened from disk.
    return (
        "// Generated by scripts/gen_demo_streams.py. Do not edit.\n"
        f"window.DEMO_STREAMS = {payload};\n"
    )


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({', '.join(f'seed {s}' for s in SEEDS)})")
